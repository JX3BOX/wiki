function convertValue(value) {
    let result = value;
    Object.entries(phraseMap).forEach(([source, target]) => {
        result = result.split(source).join(target);
    });
    return [...result].map((character) => characterMap[character] || character).join("");
}

function convertMessages(value) {
    if (typeof value === "string") return convertValue(value);
    if (Array.isArray(value)) return value.map(convertMessages);
    if (!value || typeof value !== "object") return value;
    return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, convertMessages(child)]));
}

export default convertMessages(zhCN);
